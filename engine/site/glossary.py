from __future__ import annotations

from collections import defaultdict

MIN_N = 150


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{x * 100:.1f}%"


def stats(rows: list[list]) -> dict:
    """리그별: 경기 수, 정배 승률, 역배(3.0+) 승률, 무승부 비율, 오버 비율, 플러스 핸디 적중, 환급률, 평균 배당."""
    g = defaultdict(lambda: defaultdict(float))
    sport_of = {}
    for r in rows:
        try:
            sport, lg, mk, line, l, d, rr, res = r[:8]
            hs, as_ = r[12], r[13]
        except (ValueError, IndexError):
            continue
        x = g[lg]
        sport_of[lg] = sport
        if mk in ("1X2", "WL") and l and rr and l > 1 and rr > 1:
            inv = 1 / l + 1 / rr + (1 / d if d and d > 1 else 0)
            x["pay_n"] += 1
            x["pay"] += 1 / inv
            if res in (0, 1, 2):
                x["n"] += 1
                fav_home = l < rr
                x["fav"] += (res == 0) if fav_home else (res == 2)
                x["home"] += res == 0
                x["away"] += res == 2
                dog = rr if fav_home else l
                if dog >= 3.0:
                    x["dog_n"] += 1
                    x["dog"] += (res == 2) if fav_home else (res == 0)
                    x["dog_odds"] += dog
                if mk == "1X2":
                    x["x_n"] += 1
                    x["draw"] += res == 1
                    x["draw_odds"] += d or 0
        elif mk == "OU" and res in (0, 2):
            x["ou_n"] += 1
            if line:
                x["line_n"] += 1
                x["line"] += line
            x["over"] += (res == 0) == (not r[9])
        if mk == "HANDICAP" and sport == "soccer" and res in (0, 1, 2) and line and float(line).is_integer():
            x["hd_n"] += 1
            x["hd"] += res == 1
        if mk == "HANDICAP" and res in (0, 2) and line:
            x["h_n"] += 1
            x["plus"] += (res == 2) if line < 0 else (res == 0)
        if mk in ("1X2", "WL") and hs is not None and as_ is not None:
            x["tot_n"] += 1
            x["tot"] += hs + as_
    out = {}
    for lg, x in g.items():
        if x["n"] < MIN_N:
            continue
        out[lg] = {"sport": sport_of[lg], "n": int(x["n"]),
                   "fav": x["fav"] / x["n"], "home": x["home"] / x["n"], "away": x["away"] / x["n"],
                   "dog": x["dog"] / x["dog_n"] if x["dog_n"] >= 30 else None, "dog_n": int(x["dog_n"]),
                   "dog_odds": x["dog_odds"] / x["dog_n"] if x["dog_n"] else None,
                   "draw": x["draw"] / x["x_n"] if x["x_n"] >= 50 else None, "x_n": int(x["x_n"]),
                   "draw_odds": x["draw_odds"] / x["x_n"] if x["x_n"] else None,
                   "over": x["over"] / x["ou_n"] if x["ou_n"] >= 50 else None, "ou_n": int(x["ou_n"]),
                   "plus": x["plus"] / x["h_n"] if x["h_n"] >= 50 else None, "h_n": int(x["h_n"]),
                   "pay": x["pay"] / x["pay_n"] if x["pay_n"] else None,
                   "avg_total": x["tot"] / x["tot_n"] if x["tot_n"] else None,
                   "line": x["line"] / x["line_n"] if x["line_n"] >= 50 else None,
                   "hd": x["hd"] / x["hd_n"] if x["hd_n"] >= 50 else None, "hd_n": int(x["hd_n"])}
    return out


def _poi(lam: float, k: int) -> float:
    import math
    return math.exp(-lam) * lam ** k / math.factorial(k)


def _frac(o: float) -> str:
    from fractions import Fraction
    f = Fraction(o - 1).limit_denominator(20)
    return f"{f.numerator}/{f.denominator}"


def _ml(o: float) -> str:
    return f"+{(o - 1) * 100:.0f}" if o >= 2 else f"−{100 / (o - 1):.0f}"


def bands(rows: list[list]) -> list[tuple[str, int, float, float]]:
    """정배 배당 구간별: (구간, 경기 수, 실제 승률, 배당이 말한 확률)."""
    cuts = [(1.0, 1.2), (1.2, 1.4), (1.4, 1.6), (1.6, 1.8), (1.8, 2.0), (2.0, 2.5)]
    acc = {c: [0, 0, 0.0] for c in cuts}
    for r in rows:
        try:
            _sp, _lg, mk, _line, l, d, rr, res = r[:8]
        except ValueError:
            continue
        if mk not in ("1X2", "WL") or res not in (0, 1, 2) or not (l and rr and l > 1 and rr > 1):
            continue
        fav_home = l < rr
        o = min(l, rr)
        inv = 1 / l + 1 / rr + (1 / d if d and d > 1 else 0)
        for c in cuts:
            if c[0] <= o < c[1]:
                a = acc[c]
                a[0] += 1
                a[1] += (res == 0) if fav_home else (res == 2)
                a[2] += (1 / o) / inv
    return [(f"{c[0]:.1f}~{c[1]:.1f}", a[0], a[1] / a[0], a[2] / a[0]) for c, a in acc.items() if a[0] >= 30]


def _rows(st: dict, key: str, head: list[str], fmt, sport: str | None = None, n_key: str = "n", top: int = 12):
    lst = [(lg, s) for lg, s in st.items() if s.get(key) is not None and (sport is None or s["sport"] == sport)]
    lst.sort(key=lambda x: -x[1][n_key])
    return head, [fmt(lg, s) for lg, s in lst[:top]]


def _avg(st: dict, key: str, n_key: str = "n", sport: str | None = None) -> tuple[float | None, int]:
    num = den = 0.0
    for s in st.values():
        if s.get(key) is None or (sport and s["sport"] != sport):
            continue
        num += s[key] * s[n_key]
        den += s[n_key]
    return (num / den if den else None), int(den)


