    cat = {"정배": "기본", "역배": "기본", "프로토-승부식": "기본", "단폴": "조합·구매", "폴더": "조합·구매", "승무패": "마켓", "핸디캡": "마켓",
           "언더오버": "마켓", "배당률": "배당·확률", "환급률": "배당·확률"}
    for t in out:
        t.setdefault("cat", cat.get(t["slug"], "기본"))
        t["short"] = t["lead"].split(". ")[0].rstrip(".") + "."
        import re as _re
        m = _re.search(r"\d+(?:\.\d+)?%", t["lead"])
        t["kpi"] = m.group(0) if m else ""
    for t in out:
        ch = t["term"][-1]
        bat = "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 != 0
        t["ran"] = t["term"] + ("이란" if bat else "란")
    return out
